"""Real-model evaluation of the harness itself.

1. A/A calibration: the same model against itself. Any 'regression' here is a false alarm, so this
   measures the noise the statistics have to absorb.
2. Candidates with known differences: a smaller model, another vendor, and a deliberately careless
   system prompt (expected to regress the refund-safety cases).

  GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --repeats 5 --aa 3
"""

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "AGENTREG_LLM":
        os.environ.setdefault(k, v)

from agentreg.compare import compare_suites  # noqa: E402
from agentreg.models import Config, Suite  # noqa: E402

SAMPLES = ROOT / "agentreg" / "samples"


async def main(repeats: int, aa: int, out: Path):
    suite = Suite.model_validate_json((SAMPLES / "order_support.json").read_text())
    prompts = json.loads((SAMPLES / "prompts.json").read_text())
    flash = Config(label="baseline", provider="gemini", model="gemini-2.5-flash")
    rows, reports = [], []

    async def one(name, cand, expect):
        rep = await compare_suites(suite, flash, cand, repeats, judge_provider=None)
        reports.append((name, rep))
        rows.append((name, expect, rep))
        print(name, rep.verdict, rep.counts, flush=True)

    for i in range(aa):
        await one(
            f"A/A #{i + 1}: flash vs flash",
            Config(label="candidate", provider="gemini", model="gemini-2.5-flash"),
            "no regression",
        )
    await one(
        "flash vs flash-lite",
        Config(label="candidate", provider="gemini", model="gemini-2.5-flash-lite"),
        "unknown",
    )
    await one(
        "flash vs gpt-5-nano",
        Config(label="candidate", provider="openai", model="gpt-5-nano"),
        "unknown",
    )
    await one(
        "flash: careful vs careless prompt",
        Config(
            label="candidate",
            provider="gemini",
            model="gemini-2.5-flash",
            system=prompts["careless"],
        ),
        "regression on refund safety",
    )

    aa_reps = [r for n, r in reports if n.startswith("A/A")]
    L = [
        "# Evaluation results",
        "",
        f"Generated by `evals/run.py` ({repeats} runs per case per side, alpha 0.1, 10 cases in the order-support suite).",
        "",
        "## Summary",
        "",
        "| comparison | expected | verdict | regressions | improvements | changed | unchanged | cost |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, exp, r in rows:
        L.append(
            f"| {name} | {exp} | **{r.verdict}** | {r.counts['regression']} | {r.counts['improvement']} | {r.counts['changed']} | {r.counts['same']} | ${r.cost_usd:.3f} |"
        )
    n_cases = sum(len(r.cases) for r in aa_reps)
    false_reg = sum(r.counts["regression"] for r in aa_reps)
    L += [
        "",
        f"**A/A calibration:** {false_reg} false regressions in {n_cases} case-comparisons across {len(aa_reps)} runs "
        f"({false_reg / max(n_cases, 1):.1%}). 'changed' counts show behavioral noise the harness reports but does not call a regression.",
        "",
    ]
    for name, r in reports:
        if name.startswith("A/A"):
            continue
        L += [
            f"## {name}",
            "",
            "| case | baseline pass | candidate pass | p (worse by chance) | verdict | why |",
            "|---|---|---|---|---|---|",
        ]
        for c in r.cases:
            L.append(
                f"| {c.case_id} | {c.base.passed}/{c.base.runs} | {c.cand.passed}/{c.cand.runs} | {c.p_regress:.3f} | {c.verdict} | {'; '.join(c.reasons)[:110]} |"
            )
        L.append("")
    degraded = sorted({d for _, r in reports for d in r.degraded})
    if degraded:
        L += ["## Run notes (from the harness)", ""] + [f"- {d}" for d in degraded] + [""]
    out.write_text("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=5)
    ap.add_argument("--aa", type=int, default=3)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    asyncio.run(main(a.repeats, a.aa, a.out))
